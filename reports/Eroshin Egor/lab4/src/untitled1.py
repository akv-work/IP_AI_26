    print(f" Выполняется: {exp_name}...")


    results = model.track(
        source="traffic_video.mp4",
        tracker=cfg_file,
        conf=0.25,
        stream=True,
        verbose=False
    )

    track_lengths = defaultdict(int)
    for r in results:
        if r.boxes is not None and r.boxes.id is not None:
            ids = r.boxes.id.cpu().numpy().astype(int)
            for track_id in ids:
                track_lengths[track_id] += 1

    total_ids = len(track_lengths)
    avg_len = np.mean(list(track_lengths.values())) if total_ids > 0 else 0
    stats.append((exp_name, total_ids, round(avg_len, 1)))

