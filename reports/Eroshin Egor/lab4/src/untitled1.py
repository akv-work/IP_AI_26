# 1. Функция для безопасного создания кастомных конфигов на основе встроенных
def make_tracker_cfg(base_name, modifications, save_filename):
    # Путь к встроенным конфигам ultralytics
    base_cfg_path = Path(ultralytics.__file__).parent / "cfg" / "trackers" / f"{base_name}.yaml"

    with open(base_cfg_path, 'r') as f:
        cfg = yaml.safe_load(f)


    cfg.update(modifications)

    with open(save_filename, 'w') as f:
        yaml.dump(cfg, f)
    print(f" Создан конфиг: {save_filename}")


